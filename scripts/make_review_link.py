#!/usr/bin/env python3
"""Generate the no-login review link for the review-only TEST couple (v11.9.1).

Writes, mode 600, outside the repo (never commit, never print):
  /workspace/secrets/review-link.env            REVIEW_LINK_URL + account values
  /workspace/secrets/review-link-seed.sql       creates the 2 test accounts + couple + review_users rows (bcrypt hashes only, no passwords)
  /workspace/secrets/review-link-seed-down.sql  removes them again
Run after supabase_migration_v11_9_1_review_link.sql. Prints only file names.
Bcrypt hashes come from a local Postgres (pgcrypto); PG* env selects it (default localhost:55432 postgres).
"""
import base64, json, os, secrets, string, subprocess, sys, uuid

OUT = os.environ.get('REVIEW_OUT_DIR', '/workspace/secrets')
APP = 'https://jkangmin95-maker.github.io/saibot/'


def bcrypt(pw):
    env = dict(os.environ)
    env.setdefault('PGHOST', 'localhost'); env.setdefault('PGPORT', '55432'); env.setdefault('PGUSER', 'postgres')
    sql = "\\set pw '%s'\nselect extensions.crypt(:'pw', extensions.gen_salt('bf', 10));\n" % pw  # pw is [A-Za-z0-9] only
    db = env.get('REVIEW_HASH_DB', 'urisai_hash_tmp')
    subprocess.run(['psql', '-qX', '-d', 'postgres', '-c', f'drop database if exists {db}', '-c', f'create database {db}'], env=env, check=True, capture_output=True)
    subprocess.run(['psql', '-qX', '-d', db, '-c', 'create schema extensions; create extension pgcrypto with schema extensions;'], env=env, check=True, capture_output=True)
    r = subprocess.run(['psql', '-qXtA', '-d', db, '-f', '-'], input=sql, env=env, check=True, capture_output=True, text=True)
    subprocess.run(['psql', '-qX', '-d', 'postgres', '-c', f'drop database {db}'], env=env, check=True, capture_output=True)
    h = r.stdout.strip()
    assert h.startswith('$2a$10$') and len(h) == 60
    return h


def q(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    alnum = string.ascii_letters + string.digits
    tag = ''.join(secrets.choice(string.ascii_lowercase + string.digits) for _ in range(10))
    acc = {}
    for r in ('a', 'b'):
        acc[r] = {
            'id': str(uuid.uuid4()),
            'email': f'review-{r}-{tag}@urisai-review.example.com',
            'pw': ''.join(secrets.choice(alnum) for _ in range(40)),
        }
        acc[r]['hash'] = bcrypt(acc[r]['pw'])
    code = 'S2-' + ''.join(secrets.choice(string.ascii_uppercase + string.digits) for _ in range(6))
    k = base64.urlsafe_b64encode(json.dumps({'v': 1, 'a': [acc['a']['email'], acc['a']['pw']], 'b': [acc['b']['email'], acc['b']['pw']]},
                                            separators=(',', ':')).encode()).decode().rstrip('=')
    url = APP + '?review=1#k=' + k

    users = []
    for r, name in (('a', '검수 나'), ('b', '검수 연인')):
        a = acc[r]
        users.append(f"""insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change)
values ('00000000-0000-0000-0000-000000000000', {q(a['id'])}, 'authenticated', 'authenticated', {q(a['email'])}, {q(a['hash'])}, now(),
  '{{"provider":"email","providers":["email"]}}', '{{"review_test":true}}', now(), now(), '', '', '', '');
insert into auth.identities (provider_id, user_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values ({q(a['id'])}, {q(a['id'])}, jsonb_build_object('sub', {q(a['id'])}, 'email', {q(a['email'])}, 'email_verified', true), 'email', now(), now(), now());""")
    seed = f"""-- GENERATED by scripts/make_review_link.py. Review-only TEST couple for the no-login review link. Never commit.
-- Contains bcrypt hashes only (no passwords). Apply after supabase_migration_v11_9_1_review_link.sql.
begin;
do $$ begin
  if (select count(*) from private.review_users where kind = 'owner') <> 1 then raise exception 'expected exactly 1 owner reviewer before seeding'; end if;
  if exists (select 1 from auth.users where id in ({q(acc['a']['id'])}, {q(acc['b']['id'])}) or email in ({q(acc['a']['email'])}, {q(acc['b']['email'])})) then
    raise exception 'test accounts already exist';
  end if;
end $$;
{chr(10).join(users)}
insert into public.couples (code, user_a, user_b, name_a, name_b, warmth_temp, completed_count)
values ({q(code)}, {q(acc['a']['id'])}, {q(acc['b']['id'])}, '검수 나', '검수 연인', 37.5, 0);
insert into private.review_users (user_id, kind) values ({q(acc['a']['id'])}, 'test'), ({q(acc['b']['id'])}, 'test');
do $$ begin
  if (select count(*) from private.review_users) <> 3
     or (select count(*) from private.review_users where kind = 'owner') <> 1
     or (select count(*) from private.review_users where kind = 'test') <> 2 then
    raise exception 'review_users must hold exactly 1 owner + 2 test accounts';
  end if;
  if exists (select 1 from private.review_users r join auth.identities i on i.user_id = r.user_id
             where r.kind = 'test' and i.provider <> 'email') then
    raise exception 'a test reviewer has a non-email identity';
  end if;
end $$;
commit;
"""
    down = f"""-- GENERATED by scripts/make_review_link.py. Removes the review-only TEST couple. Never commit.
begin;
delete from public.couples where code = {q(code)} and user_a = {q(acc['a']['id'])};
delete from private.review_users where user_id in ({q(acc['a']['id'])}, {q(acc['b']['id'])});
delete from auth.identities where user_id in ({q(acc['a']['id'])}, {q(acc['b']['id'])}) and provider = 'email';
delete from auth.users where id in ({q(acc['a']['id'])}, {q(acc['b']['id'])}) and email like 'review-%@urisai-review.example.com';
commit;
"""
    env = f"""# 우리사이 review link (v11.9.1, test couple {code}). Never commit or print. Generated by scripts/make_review_link.py.
REVIEW_LINK_URL={url}
REVIEW_COUPLE_CODE={code}
REVIEW_A_ID={acc['a']['id']}
REVIEW_A_EMAIL={acc['a']['email']}
REVIEW_A_PASSWORD={acc['a']['pw']}
REVIEW_B_ID={acc['b']['id']}
REVIEW_B_EMAIL={acc['b']['email']}
REVIEW_B_PASSWORD={acc['b']['pw']}
"""
    os.makedirs(OUT, mode=0o700, exist_ok=True)
    old = os.umask(0o077)
    try:
        for name, body in (('review-link.env', env), ('review-link-seed.sql', seed), ('review-link-seed-down.sql', down)):
            p = os.path.join(OUT, name)
            with open(p, 'w') as f:
                f.write(body)
            os.chmod(p, 0o600)
            print('wrote', p)
    finally:
        os.umask(old)


if __name__ == '__main__':
    sys.exit(main())
